import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

function sanitizeCertificateText(value: string): string {
  return value
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[^\x20-\x7E\xA0-\xFF]/g, ' ');
}

export interface AuditTrailMetadata {
  certificateId: string;
  fileName: string;
  originalSha256: string;
  signedAtUtc: string;
  signedPageNumber: number;
  signerName?: string;
  signerEmail?: string;
  executionMode: '100% Client-Side Browser (Zero Upload)' | 'PdfPixels Stateless Pipeline';
}

export async function appendAuditTrailCertificatePage(
  pdf: PDFDocument,
  meta: AuditTrailMetadata,
): Promise<void> {
  const fontBold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const fontRegular = await pdf.embedFont(StandardFonts.Helvetica);
  const fontMono = await pdf.embedFont(StandardFonts.Courier);

  const page = pdf.addPage([612, 792]);
  const { width, height } = page.getSize();

  page.drawRectangle({
    x: 42,
    y: height - 122,
    width: width - 84,
    height: 76,
    color: rgb(0.95, 0.97, 1),
    borderColor: rgb(0.24, 0.42, 0.85),
    borderWidth: 1,
  });

  page.drawText('ELECTRONIC SIGNATURE AUDIT TRAIL & VERIFICATION CERTIFICATE', {
    x: 58,
    y: height - 76,
    size: 12,
    font: fontBold,
    color: rgb(0.11, 0.22, 0.52),
  });
  page.drawText(
    'Issued in accordance with US ESIGN Act (15 U.S.C. 7001), UETA, and EU eIDAS Standard Verification.',
    {
      x: 58,
      y: height - 98,
      size: 9,
      font: fontRegular,
      color: rgb(0.32, 0.37, 0.48),
    },
  );

  const rows: Array<[string, string, boolean?]> = [
    ['Certificate ID', meta.certificateId, true],
    ['Document Name', sanitizeCertificateText(meta.fileName), false],
    ['Execution Mode', meta.executionMode, false],
    ['Completion Timestamp (UTC)', meta.signedAtUtc, true],
    ['Original Document SHA-256', meta.originalSha256, true],
    ['Signature Page Index', `Page ${meta.signedPageNumber}`, false],
    ['Signer Name', sanitizeCertificateText(meta.signerName?.trim() || 'Self-Signed / Authorized Signer'), false],
    ['Signer Identifier', sanitizeCertificateText(meta.signerEmail?.trim() || 'Local Verified Session'), false],
  ];

  let yCursor = height - 160;
  for (const [label, val, mono] of rows) {
    page.drawRectangle({
      x: 42,
      y: yCursor - 28,
      width: width - 84,
      height: 38,
      color: rgb(0.99, 0.99, 1),
      borderColor: rgb(0.87, 0.9, 0.94),
      borderWidth: 0.75,
    });
    page.drawText(label.toUpperCase(), {
      x: 56,
      y: yCursor - 6,
      size: 7.5,
      font: fontBold,
      color: rgb(0.4, 0.46, 0.56),
    });
    page.drawText(val.slice(0, 76), {
      x: 56,
      y: yCursor - 20,
      size: mono ? 9 : 10,
      font: mono ? fontMono : fontRegular,
      color: rgb(0.09, 0.12, 0.18),
    });
    yCursor -= 46;
  }

  page.drawText(
    'Cryptographic Integrity Note: Original SHA-256 digest captures the exact pre-signature PDF bitstream.',
    {
      x: 42,
      y: 78,
      size: 8.5,
      font: fontRegular,
      color: rgb(0.38, 0.44, 0.54),
    },
  );
  page.drawText(
    'Generated by PdfPixels Document Signing Engine · Zero server retention.',
    {
      x: 42,
      y: 62,
      size: 8.5,
      font: fontRegular,
      color: rgb(0.38, 0.44, 0.54),
    },
  );
}
