type FormTemplateType = 'w9' | 'w8ben';
type TaxClassification = 'individual' | 'ccorp' | 'scorp' | 'partnership' | 'trust' | 'llc';

async function createBlankTaxTemplatePdf(formType: FormTemplateType): Promise<File> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([612, 792]);
  const fontBold = await doc.embedFont(StandardFonts.HelveticaBold);
  const fontReg = await doc.embedFont(StandardFonts.Helvetica);

  page.drawRectangle({
    x: 36,
    y: 700,
    width: 540,
    height: 56,
    borderColor: rgb(0.15, 0.2, 0.28),
    borderWidth: 1.5,
  });
  page.drawText(
    formType === 'w9'
      ? 'Form W-9 (Rev. March 2024) - Request for Taxpayer Identification Number'
      : 'Form W-8BEN - Certificate of Foreign Status of Beneficial Owner (US Tax)',
    { x: 48, y: 734, size: 12, font: fontBold, color: rgb(0.08, 0.1, 0.14) },
  );
  page.drawText(
    'Generated by PdfPixels Client-Side Tax Form Studio (Local Zero-Upload Mode)',
    { x: 48, y: 714, size: 9, font: fontReg, color: rgb(0.35, 0.4, 0.48) },
  );

  const labels =
    formType === 'w9'
      ? [
          ['Line 1: Legal Name (as shown on income tax return)', 660],
          ['Line 2: Business Name / Disregarded Entity Name', 610],
          ['Line 3: Federal Tax Classification', 560],
          ['Line 5: Street Address (number, apt, or suite no.)', 510],
          ['Line 6: City, State, and ZIP Code', 460],
          ['Part I: Taxpayer Identification Number (SSN or EIN)', 410],
          ['Part II: Certification & Authorized Signature', 235],
        ]
      : [
          ['Line 1: Name of Individual Who is the Beneficial Owner', 660],
          ['Line 2: Country of Citizenship', 610],
          ['Line 3: Permanent Residence Address & Country', 560],
          ['Line 6: Foreign Tax Identifying Number (FTIN)', 510],
          ['Line 9-10: Tax Treaty Claim Country & Article', 460],
          ['Part III: Certification, Signature & Capacity', 235],
        ];

  for (const [text, y] of labels) {
    page.drawText(String(text), {
      x: 42,
      y: Number(y),
      size: 9.5,
      font: fontBold,
      color: rgb(0.16, 0.2, 0.28),
    });
    page.drawLine({
      start: { x: 42, y: Number(y) - 24 },
      end: { x: 570, y: Number(y) - 24 },
      thickness: 0.75,
      color: rgb(0.75, 0.78, 0.84),
    });
  }

  const bytes = await doc.save();
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  return new File([copy.buffer], formType === 'w9' ? 'irs-form-w9-template.pdf' : 'irs-form-w8ben-template.pdf', {
    type: 'application/pdf',
  });
}

export function IrsW9Workspace() {
  const [formType, setFormType] = useState<FormTemplateType>('w9');
  const [pdfFile, setPdfFile] = useState<File | null>(null);
  const [detectedAcroCount, setDetectedAcroCount] = useState<number>(0);

  // Tax form fields
  const [legalName, setLegalName] = useState('');
  const [businessName, setBusinessName] = useState('');
  const [taxClass, setTaxClass] = useState<TaxClassification>('individual');
  const [llcCode, setLlcCode] = useState('C');
  const [exemptPayeeCode, setExemptPayeeCode] = useState('');
  const [streetAddress, setStreetAddress] = useState('');
  const [cityStateZip, setCityStateZip] = useState('');
  const [citizenshipCountry, setCitizenshipCountry] = useState('United States');
  const [tinType, setTinType] = useState<'ssn' | 'ein' | 'ftin'>('ssn');
  const [tinValue, setTinValue] = useState('');
  const [certDate, setCertDate] = useState(() => new Date().toISOString().split('T')[0]);
  const [flattenPdf, setFlattenPdf] = useState(true);
  const [includeAuditTrail, setIncludeAuditTrail] = useState(true);

  // Signature state
  const [sigMode, setSigMode] = useState<'draw' | 'type'>('draw');
  const [typedSignature, setTypedSignature] = useState('');
  const [sigDataUrl, setSigDataUrl] = useState<string | null>(null);
  const drawCanvasRef = useRef<HTMLCanvasElement>(null);
  const drawingRef = useRef(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const [isProcessing, setIsProcessing] = useState(false);
  const [resultUrl, setResultUrl] = useState<string | null>(null);
  const [resultSize, setResultSize] = useState(0);
  const [resultName, setResultName] = useState('completed-form-w9.pdf');

  useEffect(() => {
    return () => {
      if (resultUrl?.startsWith('blob:')) URL.revokeObjectURL(resultUrl);
    };
  }, [resultUrl]);

  useEffect(() => {
    const canvas = drawCanvasRef.current;
    if (!canvas || sigMode !== 'draw') return;
    canvas.width = 560;
    canvas.height = 140;
    const ctx = canvas.getContext('2d');
    if (ctx) {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ctx.lineWidth = 3;
      ctx.lineCap = 'round';
      ctx.strokeStyle = '#0f172a';
    }
  }, [sigMode, pdfFile]);

  useEffect(() => {
    if (sigMode !== 'type' || !typedSignature.trim()) return;
    const c = document.createElement('canvas');
    c.width = 560;
    c.height = 140;
    const ctx = c.getContext('2d');
    if (!ctx) return;
    ctx.font = 'italic 46px Georgia, cursive';
    ctx.fillStyle = '#0f172a';
    ctx.textBaseline = 'middle';
    ctx.fillText(typedSignature, 24, 72);
    setSigDataUrl(c.toDataURL('image/png'));
  }, [sigMode, typedSignature]);

  const inspectUploadedPdf = useCallback(async (file: File) => {
    setPdfFile(file);
    setResultUrl(null);
    try {
      const buf = await file.arrayBuffer();
      const doc = await PDFDocument.load(buf, { ignoreEncryption: true });
      const fields = doc.getForm().getFields();
      setDetectedAcroCount(fields.length);
      toast.success(
        fields.length > 0
          ? `Loaded ${file.name} (${fields.length} AcroForm fields detected cleanly in browser)`
          : `Loaded ${file.name} (Overlay mode ready in browser)`,
      );
    } catch {
      setDetectedAcroCount(0);
      toast.warning('Loaded PDF cleanly in overlay mode.');
    }
  }, []);

  const handleUseBlankTemplate = async (nextType: FormTemplateType) => {
    setFormType(nextType);
    if (nextType === 'w8ben') setTinType('ftin');
    else setTinType('ssn');
    const blank = await createBlankTaxTemplatePdf(nextType);
    await inspectUploadedPdf(blank);
  };

  const handleDrawPointer = (action: 'down' | 'move' | 'up', e?: React.MouseEvent<HTMLCanvasElement>) => {
    const canvas = drawCanvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;
    if (action === 'up') {
      if (drawingRef.current) {
        drawingRef.current = false;
        setSigDataUrl(canvas.toDataURL('image/png'));
      }
      return;
    }
    if (!e) return;
    const rect = canvas.getBoundingClientRect();
    const x = ((e.clientX - rect.left) / rect.width) * canvas.width;
    const y = ((e.clientY - rect.top) / rect.height) * canvas.height;
    if (action === 'down') {
      drawingRef.current = true;
      ctx.beginPath();
      ctx.moveTo(x, y);
    } else if (action === 'move' && drawingRef.current) {
      ctx.lineTo(x, y);
      ctx.stroke();
    }
  };

  const handleGenerateSignedForm = async () => {
    if (!legalName.trim()) {
      toast.error('Please enter your Legal Name (Line 1).');
      return;
    }
    setIsProcessing(true);
    try {
      const targetFile = pdfFile ?? (await createBlankTaxTemplatePdf(formType));
      if (!pdfFile) setPdfFile(targetFile);

      const inputBuf = await targetFile.arrayBuffer();
      const sha256 = await computeSha256Hex(inputBuf);
      const pdf = await PDFDocument.load(inputBuf, { ignoreEncryption: true });

      // Attempt AcroForm population by common IRS field keywords
      const form = pdf.getForm();
      const acroFields = form.getFields();
      let mappedAcro = 0;

      for (const field of acroFields) {
        const lower = field.getName().toLowerCase();
        try {
          if ('setText' in field && typeof field.setText === 'function') {
            if (lower.includes('f1_01') || (lower.includes('name') && !lower.includes('business'))) {
              field.setText(legalName);
              mappedAcro += 1;
            } else if (lower.includes('f1_02') || lower.includes('business')) {
              field.setText(businessName);
              mappedAcro += 1;
            } else if (lower.includes('f1_07') || lower.includes('address')) {
              field.setText(streetAddress);
              mappedAcro += 1;
            } else if (lower.includes('f1_08') || lower.includes('city') || lower.includes('zip')) {
              field.setText(cityStateZip);
              mappedAcro += 1;
            } else if (lower.includes('ssn') || lower.includes('ein') || lower.includes('tin') || lower.includes('f1_1')) {
              if (tinValue.trim()) {
                field.setText(tinValue);
                mappedAcro += 1;
              }
            } else if (lower.includes('country') || lower.includes('citizen')) {
              field.setText(citizenshipCountry);
              mappedAcro += 1;
            }
          } else if ('check' in field && typeof field.check === 'function') {
            if (taxClass === 'individual' && lower.includes('c1_1[0]')) field.check();
            if (taxClass === 'ccorp' && lower.includes('c1_1[1]')) field.check();
            if (taxClass === 'scorp' && lower.includes('c1_1[2]')) field.check();
            if (taxClass === 'partnership' && lower.includes('c1_1[3]')) field.check();
            if (taxClass === 'trust' && lower.includes('c1_1[4]')) field.check();
            if (taxClass === 'llc' && lower.includes('c1_1[5]')) field.check();
          }
        } catch {
          // Ignore individual uneditable field mismatch
        }
      }

      const font = await pdf.embedFont(StandardFonts.Helvetica);
      const fontBold = await pdf.embedFont(StandardFonts.HelveticaBold);
      const firstPage = pdf.getPage(0);

      // Stamp structured overlay values cleanly on template layout (or fallback when uploaded PDF has no matching AcroForm fields)
      if (mappedAcro === 0) {
        firstPage.drawText(legalName, { x: 46, y: 642, size: 11, font: fontBold, color: rgb(0.05, 0.08, 0.14) });
        if (businessName.trim()) {
          firstPage.drawText(businessName, { x: 46, y: 592, size: 10.5, font, color: rgb(0.08, 0.1, 0.15) });
        }
        const classLabel =
          formType === 'w9'
            ? `${taxClass.toUpperCase()}${taxClass === 'llc' ? ` (Tax Code: ${llcCode})` : ''}${exemptPayeeCode ? ` · Exempt: ${exemptPayeeCode}` : ''}`
            : citizenshipCountry;
        firstPage.drawText(classLabel, { x: 46, y: 542, size: 10, font, color: rgb(0.08, 0.1, 0.15) });
        if (streetAddress.trim()) {
          firstPage.drawText(streetAddress, { x: 46, y: 492, size: 10, font, color: rgb(0.08, 0.1, 0.15) });
        }
        if (cityStateZip.trim()) {
          firstPage.drawText(cityStateZip, { x: 46, y: 442, size: 10, font, color: rgb(0.08, 0.1, 0.15) });
        }
        if (tinValue.trim()) {
          firstPage.drawText(`${tinType.toUpperCase()}: ${tinValue}`, {
            x: 46,
            y: 392,
            size: 11,
            font: fontBold,
            color: rgb(0.05, 0.08, 0.14),
          });
        }
      }

      if (sigDataUrl) {
        const b64 = sigDataUrl.split(',')[1] || '';
        const bin = atob(b64);
        const bytes = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i += 1) bytes[i] = bin.charCodeAt(i);
        const embeddedSig = await pdf.embedPng(bytes);
        firstPage.drawImage(embeddedSig, { x: 48, y: 165, width: 175, height: 48 });
      }
      firstPage.drawText(`Date: ${certDate}`, { x: 360, y: 185, size: 10, font, color: rgb(0.1, 0.12, 0.18) });

      if (flattenPdf && acroFields.length > 0) {
        try {
          form.flatten();
        } catch {
          // Safe fallback if official IRS XFA hybrid prevents flatten
        }
      }

      if (includeAuditTrail) {
        const certId = `PP-TAX-${Date.now().toString(36).toUpperCase()}`;
        await appendAuditTrailCertificatePage(pdf, {
          certificateId: certId,
          fileName: targetFile.name,
          originalSha256: sha256,
          signedAtUtc: new Date().toISOString(),
          signedPageNumber: 1,
          signerName: legalName,
          signerEmail: `${formType.toUpperCase()} Certification`,
          executionMode: '100% Client-Side Browser (Zero Upload)',
        });
      }

      const out = await pdf.save();
      const copy = new Uint8Array(out.byteLength);
      copy.set(out);
      const blob = new Blob([copy.buffer], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);
      setResultUrl((prev) => {
        if (prev?.startsWith('blob:')) URL.revokeObjectURL(prev);
        return url;
      });
      setResultSize(blob.size);
      setResultName(`${formType === 'w9' ? 'IRS-Form-W9' : 'IRS-Form-W8BEN'}-${legalName.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.pdf`);
      toast.success(`Completed ${formType.toUpperCase()} PDF generated locally in browser memory!`);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : 'Failed to build signed tax PDF.');
    } finally {
      setIsProcessing(false);
    }
  };

  const handleDownload = () => {
    if (!resultUrl) return;
    triggerDownloadWithSmartlink(
      () => {
        const a = document.createElement('a');
        a.href = resultUrl;
        a.download = resultName;
        document.body.appendChild(a);
        a.click();
        a.remove();
        toast.success('Downloaded completed tax PDF!');
      },
      {
        originalSize: pdfFile?.size || resultSize,
        processedSize: resultSize,
        formatLabel: 'PDF',
        fileName: resultName,
      },
    );
  };

  const handleReset = () => {
    if (resultUrl?.startsWith('blob:')) URL.revokeObjectURL(resultUrl);
    setPdfFile(null);
    setResultUrl(null);
    setResultSize(0);
    setLegalName('');
    setBusinessName('');
    setStreetAddress('');
    setCityStateZip('');
    setTinValue('');
    setSigDataUrl(null);
  };

  return (
    <div className="container mx-auto px-4 lg:px-8 py-8 max-w-6xl">
      <ToolPageHeader
        title="IRS Form W-9 & W-8BEN Fill, Sign & Flatten"
        description="Fill out, electronically sign, and flatten IRS Form W-9 or Form W-8BEN PDFs 100% locally in browser memory. SSNs, EINs, and signatures never leave your device."
        icon={<FileCheck2 className="h-7 w-7 text-white" />}
        onReset={handleReset}
      />
      <ToolLimitNotice
        limits={[
          'Supports IRS Form W-9 (US Persons/LLCs/Corporations) & Form W-8BEN (International Contractors)',
          'Upload any official IRS PDF or generate a clean structured tax PDF instantly',
          'Flattens fields against tampering + appends optional SHA-256 ESIGN Audit Certificate',
        ]}
      />
      <PrivateModeBadge
        className="mt-4"
        description="Taxpayer IDs (SSN / EIN / FTIN), addresses, and electronic signatures stay 100% in local browser memory — zero server transmission."
      />

      <div className="mt-6 grid lg:grid-cols-12 gap-8">
        <div className="lg:col-span-7 space-y-6">
          {/* Source PDF / Template Selector */}
          <div className="rounded-2xl border bg-card p-5 space-y-4 shadow-sm">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <Button
                  type="button"
                  size="sm"
                  variant={formType === 'w9' ? 'default' : 'outline'}
                  onClick={() => void handleUseBlankTemplate('w9')}
                  className="text-xs"
                >
                  IRS Form W-9 (US)
                </Button>
                <Button
                  type="button"
                  size="sm"
                  variant={formType === 'w8ben' ? 'default' : 'outline'}
                  onClick={() => void handleUseBlankTemplate('w8ben')}
                  className="text-xs"
                >
                  IRS Form W-8BEN (Non-US)
                </Button>
              </div>
              <div>
                <input
                  ref={fileInputRef}
                  type="file"
                  accept=".pdf,application/pdf"
                  aria-label="Upload existing W-9 PDF"
                  className="hidden"
                  onChange={(e) => {
                    const f = e.target.files?.[0];
                    if (f) void inspectUploadedPdf(f);
                  }}
                />
                <Button
                  type="button"
                  size="sm"
                  variant="outline"
                  onClick={() => fileInputRef.current?.click()}
                  className="text-xs gap-1.5"
                >
                  <Upload className="w-3.5 h-3.5" />
                  {pdfFile ? `Replace PDF (${detectedAcroCount} fields)` : 'Upload Blank IRS PDF'}
                </Button>
              </div>
            </div>

            <div className="grid sm:grid-cols-2 gap-3.5 pt-2">
              <div className="space-y-1">
                <Label className="text-xs font-semibold">1. Legal Name (As on Tax Return) *</Label>
                <Input value={legalName} onChange={(e) => setLegalName(e.target.value)} placeholder="Jane M. Doe" className="h-9 text-xs" />
              </div>
              <div className="space-y-1">
                <Label className="text-xs font-semibold">2. Business / DBA Name</Label>
                <Input value={businessName} onChange={(e) => setBusinessName(e.target.value)} placeholder="Acme Consulting LLC" className="h-9 text-xs" />
              </div>

              {formType === 'w9' ? (
                <>
                  <div className="space-y-1">
                    <Label className="text-xs font-semibold">3. Federal Tax Classification</Label>
                    <Select value={taxClass} onValueChange={(v) => setTaxClass(v as TaxClassification)}>
                      <SelectTrigger className="h-9 text-xs"><SelectValue /></SelectTrigger>
                      <SelectContent>
                        <SelectItem value="individual">Individual / Sole Proprietor</SelectItem>
                        <SelectItem value="llc">Limited Liability Company (LLC)</SelectItem>
                        <SelectItem value="ccorp">C Corporation</SelectItem>
                        <SelectItem value="scorp">S Corporation</SelectItem>
                        <SelectItem value="partnership">Partnership</SelectItem>
                        <SelectItem value="trust">Trust / Estate</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>
                  <div className="grid grid-cols-2 gap-2">
                    <div className="space-y-1">
                      <Label className="text-xs font-semibold">LLC Code</Label>
                      <Input value={llcCode} onChange={(e) => setLlcCode(e.target.value.toUpperCase().slice(0, 1))} disabled={taxClass !== 'llc'} placeholder="C / S / P" className="h-9 text-xs" />
                    </div>
                    <div className="space-y-1">
                      <Label className="text-xs font-semibold">Exempt Code</Label>
                      <Input value={exemptPayeeCode} onChange={(e) => setExemptPayeeCode(e.target.value)} placeholder="Optional" className="h-9 text-xs" />
                    </div>
                  </div>
                </>
              ) : (
                <div className="space-y-1 sm:col-span-2">
                  <Label className="text-xs font-semibold">Country of Citizenship / Treaty Residence</Label>
                  <Input value={citizenshipCountry} onChange={(e) => setCitizenshipCountry(e.target.value)} placeholder="United Kingdom / Canada / Germany" className="h-9 text-xs" />
                </div>
              )}

              <div className="space-y-1">
                <Label className="text-xs font-semibold">Street Address</Label>
                <Input value={streetAddress} onChange={(e) => setStreetAddress(e.target.value)} placeholder="742 Evergreen Terrace" className="h-9 text-xs" />
              </div>
              <div className="space-y-1">
                <Label className="text-xs font-semibold">City, State / Province &amp; Postal Code</Label>
                <Input value={cityStateZip} onChange={(e) => setCityStateZip(e.target.value)} placeholder="Austin, TX 78701" className="h-9 text-xs" />
              </div>

              <div className="space-y-1">
                <Label className="text-xs font-semibold">Taxpayer ID Type</Label>
                <Select value={tinType} onValueChange={(v) => setTinType(v as 'ssn' | 'ein' | 'ftin')}>
                  <SelectTrigger className="h-9 text-xs"><SelectValue /></SelectTrigger>
                  <SelectContent>
                    <SelectItem value="ssn">Social Security Number (SSN)</SelectItem>
                    <SelectItem value="ein">Employer ID Number (EIN)</SelectItem>
                    <SelectItem value="ftin">Foreign Tax ID (FTIN)</SelectItem>
                  </SelectContent>
                </Select>
              </div>
              <div className="space-y-1">
                <Label className="text-xs font-semibold">
                  {tinType === 'ssn' ? 'SSN (XXX-XX-XXXX)' : tinType === 'ein' ? 'EIN (XX-XXXXXXX)' : 'Foreign Tax ID (FTIN)'}
                </Label>
                <Input
                  value={tinValue}
                  onChange={(e) => setTinValue(e.target.value)}
                  placeholder={tinType === 'ssn' ? '123-45-6789' : tinType === 'ein' ? '12-3456789' : 'GB-TIN-99201'}
                  className="h-9 text-xs font-mono"
                />
              </div>
            </div>

            {/* Signature Pad */}
            <div className="pt-3 border-t space-y-3">
              <div className="flex items-center justify-between">
                <Label className="text-xs font-semibold">Part II: Electronic Signature</Label>
                <Input type="date" value={certDate} onChange={(e) => setCertDate(e.target.value)} className="w-36 h-8 text-xs" />
              </div>
              <Tabs value={sigMode} onValueChange={(v) => setSigMode(v as 'draw' | 'type')}>
                <TabsList className="grid grid-cols-2 w-48 h-8">
                  <TabsTrigger value="draw" className="text-xs"><PenTool className="w-3 h-3 mr-1" /> Draw</TabsTrigger>
                  <TabsTrigger value="type" className="text-xs"><Type className="w-3 h-3 mr-1" /> Type</TabsTrigger>
                </TabsList>
                <TabsContent value="draw" className="mt-2">
                  <div className="border rounded-xl bg-white dark:bg-zinc-950 p-2 relative">
                    <canvas
                      ref={drawCanvasRef}
                      className="w-full h-24 cursor-crosshair touch-none"
                      onMouseDown={(e) => handleDrawPointer('down', e)}
                      onMouseMove={(e) => handleDrawPointer('move', e)}
                      onMouseUp={() => handleDrawPointer('up')}
                      onMouseLeave={() => handleDrawPointer('up')}
                    />
                    <Button
                      type="button"
                      size="sm"
                      variant="ghost"
                      className="absolute bottom-1.5 right-1.5 h-6 text-[10px]"
                      onClick={() => {
                        const c = drawCanvasRef.current;
                        const ctx = c?.getContext('2d');
                        if (c && ctx) ctx.clearRect(0, 0, c.width, c.height);
                        setSigDataUrl(null);
                      }}
                    >
                      <Trash2 className="w-3 h-3 mr-1" /> Clear
                    </Button>
                  </div>
                </TabsContent>
                <TabsContent value="type" className="mt-2">
                  <Input
                    value={typedSignature}
                    onChange={(e) => setTypedSignature(e.target.value)}
                    placeholder="Type legal signature name"
                    className="text-sm italic font-serif"
                  />
                </TabsContent>
              </Tabs>
            </div>

            <div className="grid sm:grid-cols-2 gap-3 pt-2 border-t text-xs">
              <div className="flex items-center justify-between rounded-xl border p-3">
                <span className="font-medium">Flatten AcroForm Fields</span>
                <Switch checked={flattenPdf} onCheckedChange={setFlattenPdf} />
              </div>
              <div className="flex items-center justify-between rounded-xl border p-3">
                <span className="font-medium flex items-center gap-1.5">
                  <ShieldCheck className="w-3.5 h-3.5 text-emerald-600" />
                  Append Audit Certificate
                </span>
                <Switch checked={includeAuditTrail} onCheckedChange={setIncludeAuditTrail} />
              </div>
            </div>

            <div className="flex gap-2">
              <Button
                type="button"
                onClick={handleGenerateSignedForm}
                disabled={isProcessing}
                className="flex-1 h-11 font-bold text-xs gap-2"
              >
                <Sparkles className="w-4 h-4" />
                {isProcessing ? 'Generating Signed PDF...' : `Generate Signed & Flattened ${formType.toUpperCase()} PDF`}
              </Button>
              <Button type="button" variant="outline" onClick={handleReset} className="h-11 px-3">
                <RotateCcw className="w-4 h-4" />
              </Button>
            </div>
          </div>
        </div>

        <div className="lg:col-span-5 space-y-5">
          {pdfFile ? (
            <div className="rounded-2xl border bg-card p-4 space-y-3 shadow-sm">
              <div className="flex items-center justify-between">
                <span className="text-xs font-semibold">PDF Form Preview</span>
                <Badge variant="outline" className="text-[10px] font-mono">{pdfFile.name}</Badge>
              </div>
              <div className="border rounded-xl overflow-hidden bg-white">
                <PdfPagePreview file={pdfFile} pageNumber={1} />
              </div>
            </div>
          ) : (
            <div className="rounded-2xl border border-dashed bg-card/50 p-6 text-center space-y-3">
              <FileCheck2 className="w-10 h-10 text-primary mx-auto opacity-80" />
              <h3 className="text-sm font-bold">Ready for IRS {formType.toUpperCase()} Completion</h3>
              <p className="text-xs text-muted-foreground leading-relaxed">
                Enter your taxpayer information on the left and click Generate Signed PDF — or upload an official IRS Form PDF from IRS.gov to map its interactive fields automatically.
              </p>
            </div>
          )}

          {resultUrl && (
            <div className="rounded-2xl border border-emerald-500/30 bg-emerald-500/[0.06] p-5 space-y-3 text-center">
              <div className="w-10 h-10 rounded-full bg-emerald-500/15 text-emerald-600 flex items-center justify-center mx-auto">
                <Check className="w-5 h-5" />
              </div>
              <div>
                <h4 className="font-bold text-sm">Signed {formType.toUpperCase()} Ready!</h4>
                <p className="text-xs text-muted-foreground">
                  Flattened locally in your browser with zero server retention.
                </p>
              </div>
              <Button onClick={handleDownload} className="w-full gap-2 font-bold">
                <Download className="w-4 h-4" />
                Download {resultName}
              </Button>
              <SmartlinkButton className="w-full justify-center" />
              <ResultScreenAd
                refreshKey={resultUrl}
                originalSize={pdfFile?.size || resultSize}
                processedSize={resultSize}
                formatLabel="PDF"
                fileName={resultName}
              />
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
